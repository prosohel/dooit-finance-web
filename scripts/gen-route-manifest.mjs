// Writes lib/breadcrumbs/route-manifest.js: every URL pattern under
// app/dashboard that has a page file. The breadcrumb links an ancestor only
// when it matches one of these, so folders with no page of their own
// (e.g. /monitoring-and-cases) render as plain text instead of 404 links.
//
// Runs automatically before `dev` and `build` (see package.json).
import { readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const appDir = join(root, "app");
const scanFrom = join(appDir, "dashboard");
const PAGE_FILE = /^page\.(js|jsx|ts|tsx)$/;

const routes = new Set();

const walk = (dir, urlSegments) => {
  const entries = readdirSync(dir, { withFileTypes: true });
  if (entries.some((e) => e.isFile() && PAGE_FILE.test(e.name))) {
    routes.add("/" + urlSegments.join("/"));
  }
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const name = entry.name;
    // Private folders and parallel-route slots never appear in the URL as-is.
    if (name.startsWith("_") || name.startsWith("@")) continue;
    // Route groups `(name)` organise files without adding a URL segment.
    const isGroup = name.startsWith("(") && name.endsWith(")");
    walk(join(dir, name), isGroup ? urlSegments : [...urlSegments, name]);
  }
};

walk(scanFrom, ["dashboard"]);

const sorted = [...routes].sort();
const out = `// GENERATED by scripts/gen-route-manifest.mjs — do not edit by hand.
// Regenerated before every \`dev\` and \`build\`.
const routeManifest = ${JSON.stringify(sorted, null, 2)};

export default routeManifest;
`;

writeFileSync(join(root, "lib", "breadcrumbs", "route-manifest.js"), out);
console.log(`route-manifest: ${sorted.length} routes`);
